/**
 * Generates the jsCode payloads for n8n Code nodes from the unit-tested
 * modules in src/. Never hand-edit build/ - edit src/ and re-run:
 *
 *   node scripts/build-code-nodes.js
 *
 * Why: the parser is covered by src/pin-parser.test.js. Pasting it into a
 * workflow by hand would let the tested copy and the running copy drift.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

/** Strip the CommonJS export block - n8n Code nodes have no module system. */
function inlineModule(relPath) {
  const src = fs.readFileSync(path.join(ROOT, relPath), 'utf8');
  const cut = src.indexOf('module.exports');
  if (cut === -1) throw new Error(`no module.exports found in ${relPath}`);
  return src.slice(0, cut).trimEnd();
}

const PARSER = inlineModule('src/pin-parser.js');
const BOARDURL = inlineModule('src/board-url.js');
// pin-resolver requires pin-parser for ETSY_LISTING_RE; inline both and drop
// the require so the Code node needs no module system.
const RESOLVER = inlineModule('src/pin-resolver.js')
  .replace(/^const \{ ETSY_LISTING_RE \} = require\('\.\/pin-parser\.js'\);$/m,
           '// ETSY_LISTING_RE is provided by the inlined pin-parser above.');

/** Workflow A / feed-probe: turn RSS items into parsed pin rows. */
const PARSE_PINS = `${PARSER}

// ---------------------------------------------------------------- n8n glue
// Generated by scripts/build-code-nodes.js from src/pin-parser.js - do not
// edit here. Mode: Run Once for All Items.

const board_slug = $('Build Feed URL').first().json.board_slug;
const rss_url = $('Build Feed URL').first().json.rss_url;

const parsed = [];
const rejected = [];

for (const item of $input.all()) {
  const raw = item.json;

  // The RSS node was set to continue on error so one dead board cannot stop
  // the run. A failed fetch arrives as an item carrying .error instead of
  // feed fields.
  if (raw && raw.error) {
    return [{
      json: {
        ok: false,
        stage: 'feed_error',
        board_slug,
        rss_url,
        message: String(raw.error.message || raw.error),
        hint: 'A 404 usually means the board was renamed or is secret. A '
            + 'timeout or 403 means Pinterest rate-limited or blocked the '
            + 'n8n server for this request.',
      },
    }];
  }

  const r = parsePin(raw, { board_slug });
  if (r.ok) parsed.push(r); else rejected.push(r);
}

if (!parsed.length && !rejected.length) {
  return [{
    json: {
      ok: false,
      stage: 'empty_feed',
      board_slug,
      rss_url,
      message: 'The feed was fetched but contained no items.',
      hint: 'Check the board slug. A private/secret board returns an empty '
          + 'or 404 feed even when the URL looks right.',
    },
  }];
}

const out = parsed.map((p) => ({ json: p }));

// A single summary item makes the result readable at a glance in the
// execution view and feeds the form's completion screen.
out.unshift({
  json: {
    _summary: true,
    ok: true,
    board_slug,
    rss_url,
    pins_in_feed: parsed.length + rejected.length,
    with_etsy_link: parsed.length,
    rejected: rejected.length,
    rejected_reasons: rejected.reduce((a, r) => {
      a[r.reason] = (a[r.reason] || 0) + 1;
      return a;
    }, {}),
    rejected_examples: rejected.slice(0, 5).map((r) => ({
      reason: r.reason, title: r.title, pin_url: r.pin_url,
    })),
    unique_listings: new Set(parsed.map((p) => p.etsy_listing_id)).size,
    first_pin_preview: parsed.length ? {
      etsy_listing_id: parsed[0].etsy_listing_id,
      etsy_url: parsed[0].etsy_url,
      title: parsed[0].title,
      description: parsed[0].description,
      image_url: parsed[0].image_url,
      image_candidates: parsed[0].image_candidates,
      pin_url: parsed[0].pin_url,
    } : null,
  },
});

return out;
`;

/** Feed probe / Workflow D: resolve the typed form fields into an rss_url. */
const BUILD_FEED_URL = `${BOARDURL}

// ---------------------------------------------------------------- n8n glue
// Generated by scripts/build-code-nodes.js from src/board-url.js - do not
// edit here. Mode: Run Once for All Items.

const f = $input.first().json;

// Form field labels become the item keys, so these must match the labels on
// the Form Trigger exactly.
const usernameInput = f['Pinterest username'] ?? f.username ?? '';
const boardInput = f['Board (slug, name, or pasted board URL)'] ?? f.board ?? '';

const r = resolveBoard(usernameInput, boardInput);

if (!r.ok) {
  // Surface the problem as data rather than throwing, so the form's ending
  // screen can explain it in plain language.
  return [{ json: { ok: false, stage: 'bad_input', message: r.error,
                    typed_username: String(usernameInput),
                    typed_board: String(boardInput) } }];
}

return [{ json: {
  ok: true,
  username: r.username,
  board_slug: r.board_slug,
  rss_url: r.rss_url,
} }];
`;

/** Resolver probe: expand the posted pin URLs into one item each. */
const PINS_TO_RESOLVE = `// Generated by scripts/build-code-nodes.js - do not edit here.
// Mode: Run Once for All Items.

const first = $input.first().json || {};
const body = first.body || first;

let urls = body.pin_urls ?? body.pinUrls ?? body.urls;
if (typeof urls === 'string') urls = urls.split(/[\\s,]+/);

if (!Array.isArray(urls) || !urls.filter(Boolean).length) {
  throw new Error('POST a JSON body like {"pin_urls":["https://www.pinterest.com/pin/123/"]}');
}

// Cap the batch so a probe can never turn into a scrape.
return urls.filter(Boolean).slice(0, 10).map((u) => ({
  json: { pin_url: String(u).trim().replace(/\\/*$/, '/') },
}));
`;

/** Resolver probe: turn each fetched pin page into a resolution result. */
const EXTRACT_DESTINATION = `${PARSER}

${RESOLVER}

// ---------------------------------------------------------------- n8n glue
// Generated by scripts/build-code-nodes.js from src/pin-parser.js and
// src/pin-resolver.js - do not edit here. Mode: Run Once for All Items.

const results = [];

for (const item of $input.all()) {
  const j = item.json || {};
  const pin_url = $('Pins To Resolve').all()
    .map((i) => i.json.pin_url)[item.pairedItem?.item ?? results.length] || j.pin_url || '';

  // HTTP Request with responseFormat=text puts the body in .data. neverError
  // keeps non-2xx responses flowing so we can report the status.
  const html = typeof j.data === 'string' ? j.data
    : typeof j.body === 'string' ? j.body : '';
  const status = j.statusCode ?? j.status ?? null;

  if (!html) {
    results.push({ json: {
      ok: false, pin_url, reason: 'empty_response', http_status: status,
      note: 'No HTML came back. A 403/429 here means Pinterest blocked the '
          + 'n8n server for unauthenticated page fetches.',
      raw_keys: Object.keys(j).slice(0, 15),
    } });
    continue;
  }

  const r = resolveEtsyFromHtml(html, { pin_url });
  results.push({ json: { pin_url, http_status: status, ...r } });
}

// Leading summary item so the probe is readable at a glance.
const okCount = results.filter((r) => r.json.ok).length;
results.unshift({ json: {
  _summary: true,
  pins_tried: results.length,
  resolved_to_etsy: okCount,
  verdict: okCount > 0
    ? 'RESOLVER WORKS - pin pages expose the Etsy link; Workflow A can use this.'
    : 'RESOLVER FAILED - see reasons below before building Workflow A.',
  reasons: results.reduce((a, r) => {
    const k = r.json.ok ? 'resolved' : (r.json.reason || 'unknown');
    a[k] = (a[k] || 0) + 1;
    return a;
  }, {}),
} });

return results;
`;

/**
 * Workflow A's Code nodes. Each entry names its dependency modules, which are
 * inlined above the node body so the Code node needs no module system.
 */
const NODE_MANIFEST = [
  { out: 'build/config-map.js', src: 'src/nodes/config-map.js', deps: [] },
  { out: 'build/boards-to-sync.js', src: 'src/nodes/boards-to-sync.js', deps: [] },
  { out: 'build/parse-pins-to-rows.js', src: 'src/nodes/parse-pins-to-rows.js',
    deps: ['parser'] },
  { out: 'build/pins-to-resolve.js', src: 'src/nodes/pins-to-resolve.js', deps: [] },
  { out: 'build/resolve-pin-result.js', src: 'src/nodes/resolve-pin-result.js',
    deps: ['parser', 'resolver'] },
  { out: 'build/group-by-listing.js', src: 'src/nodes/group-by-listing.js', deps: [] },
  { out: 'build/merge-item.js', src: 'src/nodes/merge-item.js', deps: [] },
  { out: 'build/pick-image.js', src: 'src/nodes/pick-image.js', deps: [] },
  { out: 'build/sync-summary.js', src: 'src/nodes/sync-summary.js', deps: [] },
];

const DEP_SOURCE = { parser: PARSER, resolver: RESOLVER };

const manifestTargets = {};
for (const entry of NODE_MANIFEST) {
  const body = fs.readFileSync(path.join(ROOT, entry.src), 'utf8');
  const head = entry.deps.map((d) => DEP_SOURCE[d]).join('\n\n');
  manifestTargets[entry.out] = head ? `${head}\n\n${body}` : body;
}

const targets = {
  ...manifestTargets,

  'build/parse-pins.js': PARSE_PINS,
  'build/build-feed-url.js': BUILD_FEED_URL,
  'build/probe-pins-to-resolve.js': PINS_TO_RESOLVE,
  'build/extract-destination.js': EXTRACT_DESTINATION,
};

fs.mkdirSync(path.join(ROOT, 'build'), { recursive: true });
for (const [rel, body] of Object.entries(targets)) {
  fs.writeFileSync(path.join(ROOT, rel), body);
  console.log(`wrote ${rel}  (${body.split('\n').length} lines)`);
}
